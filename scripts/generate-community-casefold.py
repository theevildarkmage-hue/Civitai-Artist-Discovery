"""Generate the Edge equivalent of Python's existing hidden-name normalization.

No downloaded data/dependency. Run using the pinned Python 3.14 / Unicode16.
"""
import json,unicodedata
from pathlib import Path
assert unicodedata.unidata_version=='16.0.0','Use pinned Unicode16 Python'
mapping={str(i):chr(i).casefold() for i in range(0x110000) if chr(i).casefold()!=chr(i)}
target=Path(__file__).resolve().parents[1]/'supabase/functions/community-v1/casefold.ts'
target.write_text('// Generated by scripts/generate-community-casefold.py; Unicode16.0.0.\n'
    '// Match local ContentProfile.casefold without V8 Unicode/version assumptions.\n'
    'const fold:Record<string,string>='+json.dumps(mapping,ensure_ascii=True,separators=(',',':'))+';\n'
    "export const casefold=(value:string)=>Array.from(value,c=>fold[String(c.codePointAt(0))]??c).join('');\n",encoding='utf-8')
print('Generated Unicode16 casefold entries:',len(mapping))
